export function presentationCopy(value){
 if(typeof value!=='string')return value;
 if(notes.has(value.trim()))return notes.get(value.trim());
 if(standalone.has(value.trim()))return value.replace(value.trim(),standalone.get(value.trim()));
 if(value.trim()==='假设数据演示策略规则，条件尚未核实，不是实时交易信号。')return '假设参数，条件尚未核实；不构成实时交易信号。';
 if(value.trim()==='Hypothetical inputs illustrate the strategy; conditions are unverified and are not a live trading signal.')return 'Hypothetical inputs; conditions remain unverified. This is not a live trading signal.';
 if(value.trim()==='这里只分配模拟额度，不发生转账。')return '设置这套策略可使用的金额，不会转入资金。';
 if(value.trim()==='This allocates simulated capital; no transfer occurs.')return 'Set the strategy budget. No funds are transferred.';
 if(value.trim()==='策略模拟使用统一账户，当前接入方案未适配这条交易路线。')return '当前账户不支持这类交易，请切换可用账户。';
 if(value.trim()==='Strategy simulation uses the unified account. This access plan does not support the route.')return 'This account does not support the selected market. Switch to a supported account.';
 const rendered=value.replace(copyPattern,key=>replacementMap.get(key)).replace(copyPattern,key=>replacementMap.get(key)).replace(/模拟 (?=\d+(?:天|时|分|秒))/g,'运行 ').replace(/\bSim (?=\d+[dhms]\b)/g,'Run ');
 return rendered===value?value:rendered.replace(/(\S)\s*·\s*$/,'$1');
}
